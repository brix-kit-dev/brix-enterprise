#!/bin/bash
set -euo pipefail

: "${BRIX_BOOTSTRAP_SUPER_ADMIN_EMAIL:?Set BRIX_BOOTSTRAP_SUPER_ADMIN_EMAIL before running this script}"
: "${BRIX_BOOTSTRAP_SUPER_ADMIN_USERNAME:?Set BRIX_BOOTSTRAP_SUPER_ADMIN_USERNAME before running this script}"
: "${BRIX_BOOTSTRAP_SUPER_ADMIN_SETUP_CODE:?Set BRIX_BOOTSTRAP_SUPER_ADMIN_SETUP_CODE before running this script}"
: "${BRIX_PLATFORM_ADMIN_SETUP_BASE_URL:?Set BRIX_PLATFORM_ADMIN_SETUP_BASE_URL before running this script}"
: "${BRIX_PLATFORM_MFA_ENCRYPTION_KEY:?Set BRIX_PLATFORM_MFA_ENCRYPTION_KEY before running this script}"

BRIX_BOOTSTRAP_SUPER_ADMIN_ENABLED="${BRIX_BOOTSTRAP_SUPER_ADMIN_ENABLED:-true}"
BRIX_BOOTSTRAP_SUPER_ADMIN_SETUP_CODE_TTL_SECONDS="${BRIX_BOOTSTRAP_SUPER_ADMIN_SETUP_CODE_TTL_SECONDS:-900}"
BRIX_BOOTSTRAP_SUPER_ADMIN_SESSION_TTL_SECONDS="${BRIX_BOOTSTRAP_SUPER_ADMIN_SESSION_TTL_SECONDS:-300}"
BRIX_PLATFORM_MFA_ISSUER="${BRIX_PLATFORM_MFA_ISSUER:-Brix}"
BRIX_PLATFORM_ADMIN_SETUP_TOKEN_TTL_SECONDS="${BRIX_PLATFORM_ADMIN_SETUP_TOKEN_TTL_SECONDS:-86400}"
BRIX_PLATFORM_ADMIN_SETUP_RETURN_URL_FOR_DEV_ONLY="${BRIX_PLATFORM_ADMIN_SETUP_RETURN_URL_FOR_DEV_ONLY:-false}"

cd /home/deploy/host-shell-standalone

# Append Bootstrap v2 settings if not present. Values must come from the
# operator's secret source; this script must not carry default credentials.
if ! grep -q '^BRIX_PLATFORM_MFA_ENCRYPTION_KEY=' .env; then
  cat >> .env <<EOF

# Platform MFA secret encryption
BRIX_PLATFORM_MFA_ISSUER=$BRIX_PLATFORM_MFA_ISSUER
BRIX_PLATFORM_MFA_ENCRYPTION_KEY=$BRIX_PLATFORM_MFA_ENCRYPTION_KEY
EOF
  echo "appended platform MFA settings to .env"
else
  echo "platform MFA settings already in .env"
fi

if ! grep -q '^BRIX_BOOTSTRAP_SUPER_ADMIN_SETUP_CODE=' .env; then
  cat >> .env <<EOF

# Platform Admin setup-link delivery
BRIX_PLATFORM_ADMIN_SETUP_BASE_URL=$BRIX_PLATFORM_ADMIN_SETUP_BASE_URL
BRIX_PLATFORM_ADMIN_SETUP_MAIL_FROM=${BRIX_PLATFORM_ADMIN_SETUP_MAIL_FROM:-}
BRIX_PLATFORM_ADMIN_SETUP_TOKEN_TTL_SECONDS=$BRIX_PLATFORM_ADMIN_SETUP_TOKEN_TTL_SECONDS
BRIX_PLATFORM_ADMIN_SETUP_RETURN_URL_FOR_DEV_ONLY=$BRIX_PLATFORM_ADMIN_SETUP_RETURN_URL_FOR_DEV_ONLY

# SUPER_ADMIN Bootstrap v2 (Layer 2C)
BRIX_BOOTSTRAP_SUPER_ADMIN_ENABLED=$BRIX_BOOTSTRAP_SUPER_ADMIN_ENABLED
BRIX_BOOTSTRAP_SUPER_ADMIN_EMAIL=$BRIX_BOOTSTRAP_SUPER_ADMIN_EMAIL
BRIX_BOOTSTRAP_SUPER_ADMIN_USERNAME=$BRIX_BOOTSTRAP_SUPER_ADMIN_USERNAME
BRIX_BOOTSTRAP_SUPER_ADMIN_SETUP_CODE=$BRIX_BOOTSTRAP_SUPER_ADMIN_SETUP_CODE
BRIX_BOOTSTRAP_SUPER_ADMIN_SETUP_CODE_TTL_SECONDS=$BRIX_BOOTSTRAP_SUPER_ADMIN_SETUP_CODE_TTL_SECONDS
BRIX_BOOTSTRAP_SUPER_ADMIN_SESSION_TTL_SECONDS=$BRIX_BOOTSTRAP_SUPER_ADMIN_SESSION_TTL_SECONDS
EOF
  echo "appended bootstrap settings to .env"
else
  echo "bootstrap settings already in .env"
fi
echo
echo "=== bootstrap env (secrets redacted) ==="
grep -E '^(BRIX_BOOTSTRAP_SUPER_ADMIN_|BRIX_PLATFORM_ADMIN_SETUP_|BRIX_PLATFORM_MFA_)' .env \
  | sed \
      -e 's/\(BRIX_BOOTSTRAP_SUPER_ADMIN_SETUP_CODE=\).*/\1****/' \
      -e 's/\(BRIX_PLATFORM_MFA_ENCRYPTION_KEY=\).*/\1****/'
